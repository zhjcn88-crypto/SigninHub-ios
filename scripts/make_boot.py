#!/usr/bin/env python3
"""生成 iOS 专用的运行时引导模块 app/_ios_boot.py。

为什么需要它
------------
后端原本是给「电脑 + 另一台设备上的浏览器」写的。搬进 iOS App 沙箱后有
四处硬伤，任意一处都会让 App「装得上但用不了」：

1. **没有 CA 证书库**
   iOS 的 CPython 用 OpenSSL，OpenSSL 不认系统 Keychain。不显式指定
   SSL_CERT_FILE，所有 https（codebuddy / trae / qoder / minimax 的签到接口）
   都会 CERTIFICATE_VERIFY_FAILED。
   → 把随包的 cacert.pem 指给 SSL_CERT_FILE 等变量。

2. **App 包只读**
   config.py 默认把 DATA_DIR 放在 backend/data（包内路径），iOS 上写入必失败。
   → SIGNBOT_DATA 指到沙箱 Library/Application Support/SigninHub。

3. **访问口令会让内置页面全站 401**
   serve() 启动时若发现 api_token 为空，会**自动生成随机口令写盘**。
   这是给「电脑端 + 手机远程连」设计的。而本 App 的页面就在 127.0.0.1，
   属于 loopback 来源，后端对「空口令 + 本机来源」本来是放行的；一旦自动
   生成了口令，WebView 手里没有它 → 所有 /api/* 返回 401，页面直接不可用，
   用户连去设置页填口令的机会都没有。
   → 关掉自动生成口令：让 serve() 走「空口令」分支，内置页面正常可用。
     安全性不受影响：服务只绑 127.0.0.1，局域网连不进来；写操作仍要过 CSRF。

4. **HOME / TMPDIR 在沙箱里不一定可写**
   → 统一钉到沙箱内确实可写的目录。
"""
from __future__ import annotations

import sys
from pathlib import Path

MARKER = "# AUTO-GENERATED by SigninHub-ios scripts/make_boot.py — 请勿手改"

TEMPLATE = '''@@MARKER@@
"""iOS 运行时引导：证书 / 数据目录 / 口令 / 临时目录。

由 main.m 在 import signbot.server **之前**最先导入。
"""

import os
import sys

_APP = os.path.dirname(os.path.abspath(__file__))
_RES = os.path.dirname(_APP)          # .app 根目录


def _writable(path):
    """实际建目录并试写一个临时文件，确认真的可写。"""
    try:
        os.makedirs(path, exist_ok=True)
        probe = os.path.join(path, ".wtest")
        with open(probe, "w", encoding="utf-8") as f:
            f.write("ok")
        os.remove(probe)
        return True
    except OSError:
        return False


def _sandbox_container():
    """返回一个确实可写的沙箱根目录。"""
    candidates = []
    home = os.environ.get("HOME")
    if home:
        candidates.append(home)
    candidates.append(os.path.expanduser("~"))

    for base in candidates:
        p = base
        for _ in range(4):
            if p and _writable(p):
                return p
            parent = os.path.dirname(p)
            if parent == p:
                break
            p = parent

    import tempfile
    return tempfile.gettempdir()


def _atomic_write_json(path, obj):
    import json
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=2)
    os.replace(tmp, path)


def _resolve_data_dir(home):
    """数据目录：外部显式设置的优先，否则在沙箱里挑一个可写的。"""
    existing = os.environ.get("SIGNBOT_DATA")
    if existing and _writable(existing):
        return existing
    for cand in (
        os.path.join(home, "Library", "Application Support", "SigninHub"),
        os.path.join(home, "Library", "SigninHub"),
        os.path.join(home, "SigninHub"),
    ):
        if _writable(cand):
            return cand
    return None


def _clear_existing_token(data_dir):
    """把已存在配置里的 api_token 清空（老版本升级过来的情况）。"""
    if not data_dir:
        return
    cfg_path = os.path.join(data_dir, "config.json")
    if not os.path.isfile(cfg_path):
        return
    try:
        import json
        with open(cfg_path, "r", encoding="utf-8-sig") as f:
            cfg = json.load(f)
    except Exception:
        return
    if not isinstance(cfg, dict):
        return
    srv = cfg.get("server")
    if not isinstance(srv, dict):
        srv = cfg["server"] = {}
    if srv.get("api_token"):
        srv["api_token"] = ""
        try:
            _atomic_write_json(cfg_path, cfg)
        except OSError:
            pass


def _disable_token_autogen():
    """关掉 serve() 的「空口令自动生成」行为。

    导入 signbot.server 之后立刻替换 `_ensure_api_token`。
    serve() 调用它时拿到空串 → 走「未设置口令」分支 →
    对 loopback 来源放行只读，写操作加 CSRF 校验。
    """
    try:
        import importlib
        srv = importlib.import_module("signbot.server")
    except Exception:
        return False

    if getattr(srv, "_ios_token_guard", False):
        return True
    srv._ios_token_guard = True

    def _ensure_api_token_ios():
        # (token, generated) —— 永远返回空口令，绝不写盘生成
        return "", False

    srv._ensure_api_token = _ensure_api_token_ios
    return True


def bootstrap():
    home = _sandbox_container()

    # ── 1) 数据目录（必须在沙箱内，包内只读）────────────────────────
    data_dir = _resolve_data_dir(home)
    if data_dir:
        os.environ["SIGNBOT_DATA"] = data_dir

    # ── 2) 临时目录 ─────────────────────────────────────────────────
    tmp = os.path.join(home, "tmp")
    if _writable(tmp):
        os.environ["TMPDIR"] = tmp

    # ── 3) CA 证书（OpenSSL 不认 Keychain，必须显式指文件）──────────
    ca_used = None
    for ca in (
        os.path.join(_RES, "cacert.pem"),
        os.path.join(_APP, "cacert.pem"),
        os.path.join(_APP, "certifi", "cacert.pem"),
    ):
        if os.path.isfile(ca):
            os.environ.setdefault("SSL_CERT_FILE", ca)
            os.environ.setdefault("REQUESTS_CA_BUNDLE", ca)
            os.environ.setdefault("CURL_CA_BUNDLE", ca)
            ca_used = ca
            break
    os.environ.pop("SSL_CERT_DIR", None)

    # ── 4) 包体只读，别写 .pyc ──────────────────────────────────────
    os.environ.setdefault("PYTHONDONTWRITEBYTECODE", "1")

    return {
        "home": home,
        "data_dir": os.environ.get("SIGNBOT_DATA"),
        "ssl_cert_file": ca_used,
    }


INFO = bootstrap()


def register_app_packages():
    """把 app_packages 按「site 目录」注册，从而支持 .pth 文件。

    为什么不能只把 app_packages 塞进 sys.path：
      一些纯 Python 包依赖 .pth 做路径注入（例如拆成多目录的发行版、
      或者带 `import` 语句的 .pth）。直接把目录放进 sys.path 会跳过
      .pth 处理，这类包就会「装上了但 import 不到」。
      site.addsitedir() 正是标准库处理这件事的入口。

    做法与 CPython 官方 iOS 范式一致：先 addsitedir(app_packages)，
    再把 app/ 放到 sys.path 前面（我们的代码优先级高于第三方包）。
    """
    import os
    import site
    import sys

    res = os.path.dirname(os.path.abspath(__file__))
    pkgs = os.path.join(res, "app_packages")
    app = res

    if os.path.isdir(pkgs):
        try:
            site.addsitedir(pkgs)
        except Exception as e:      # .pth 内容有语法错也不能让 App 起不来
            print("[ios_boot] addsitedir(%s) 失败: %s" % (pkgs, e))

    # 确保 app/ 在最前（app_packages 里若有同名模块不应遮蔽我们的代码）
    if app in sys.path:
        sys.path.remove(app)
    sys.path.insert(0, app)

    return {"app": app, "app_packages": pkgs if os.path.isdir(pkgs) else None}

def prepare_server():
    """在 serve() 之前调用：清老口令 + 关掉自动生成 + 注册 site 目录。幂等。"""
    _clear_existing_token(os.environ.get("SIGNBOT_DATA"))
    ok = _disable_token_autogen()
    INFO["token_autogen_disabled"] = ok
    try:
        INFO["site"] = register_app_packages()
    except Exception as e:
        INFO["site_error"] = str(e)
    return ok


if __name__ == "__main__":
    import json
    prepare_server()
    print(json.dumps(INFO, ensure_ascii=False, indent=2))
'''


def build() -> str:
    """把模板里的 @@MARKER@@ 换成真正的注释标记。

    不用 str.format：模板是 Python 源码，里面大量 `{}`（dict 字面量、
    格式化字符串）会被格式化成占位符，之前就因此炸过一次。
    """
    return TEMPLATE.replace("@@MARKER@@", MARKER)


def main() -> int:
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("app")
    root.mkdir(parents=True, exist_ok=True)
    target = root / "_ios_boot.py"
    target.write_text(build(), encoding="utf-8")
    print(f"[ok] generated {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
